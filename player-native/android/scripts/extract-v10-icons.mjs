// Writes `V10Icons.kt` from the icons Video.js 10's default skin ships, which the web player draws.
// Run from the repository root: node player-native/android/scripts/extract-v10-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '../../../node_modules/@videojs/html/dist/default/icons/dist/html/default');
const out = join(here, '../src/main/java/org/bccsa/luminary/player/engine/V10Icons.kt');

const ICONS = {
    play: 'play',
    pause: 'pause',
    volumeOff: 'volume-off',
    volumeLow: 'volume-low',
    volumeHigh: 'volume-high',
    quality: 'switches',
    speech: 'speech',
    speed: 'speed',
    captions: 'captions-off',
    cast: 'cast-enter',
    pip: 'pip-enter',
    fullscreenExit: 'fullscreen-exit',
    check: 'check',
};

const num = (n) => String(Math.round(n * 1000) / 1000);

function rect({ x = 0, y = 0, width, height, rx = 0 }) {
    const [X, Y, W, H, R] = [x, y, width, height, Math.min(rx, width / 2, height / 2)].map(Number);
    if (!R) return `M${num(X)} ${num(Y)}h${num(W)}v${num(H)}h${num(-W)}z`;
    return (
        `M${num(X + R)} ${num(Y)}h${num(W - 2 * R)}a${num(R)} ${num(R)} 0 0 1 ${num(R)} ${num(R)}v${num(H - 2 * R)}` +
        `a${num(R)} ${num(R)} 0 0 1 ${num(-R)} ${num(R)}h${num(-(W - 2 * R))}a${num(R)} ${num(R)} 0 0 1 ${num(-R)} ${num(-R)}` +
        `v${num(-(H - 2 * R))}a${num(R)} ${num(R)} 0 0 1 ${num(R)} ${num(-R)}z`
    );
}

const circle = ({ cx, cy, r }) => `M${num(+cx - +r)} ${num(cy)}a${r} ${r} 0 1 0 ${num(2 * r)} 0a${r} ${r} 0 1 0 ${num(-2 * r)} 0z`;

function attrs(tag) {
    const found = {};
    for (const m of tag.matchAll(/([a-z-]+)="([^"]*)"/g)) found[m[1]] = m[2];
    return found;
}

function layers(svg) {
    const result = [];
    // A `<g>` carries an opacity for its children; the others are flat.
    const body = svg.replace(/^.*?viewBox="[^"]*">/s, '').replace(/<\/svg>.*$/s, '');
    let groupAlpha = 1;
    for (const m of body.matchAll(/<(g|\/g|path|rect|circle)\b([^>]*?)\/?>/g)) {
        const [, tag, rest] = m;
        if (tag === 'g') groupAlpha = Number(attrs(rest)['fill-opacity'] ?? 1);
        else if (tag === '/g') groupAlpha = 1;
        else {
            const a = attrs(rest);
            const alpha = Number(a['fill-opacity'] ?? groupAlpha);
            const stroke = a.stroke === 'currentColor';
            const d = tag === 'path' ? a.d : tag === 'rect' ? rect(a) : circle(a);
            result.push({ d, alpha, stroke, width: Number(a['stroke-width'] ?? 0) });
        }
    }
    return result;
}

let kotlin = `// Generated by player-native/android/scripts/extract-v10-icons.mjs from the icons Video.js 10's
// default skin ships, the ones the web player draws. Do not edit.
package org.bccsa.luminary.player.engine

/** SVG path data on an 18-unit grid, in layers: some are half-opaque, and a few are outlines. */
internal object V10Icons {
    const val GRID = 18f

    class Layer(val path: String, val alpha: Float, val strokeWidth: Float)

`;
for (const [name, file] of Object.entries(ICONS)) {
    const svg = readFileSync(join(dir, `${file}.js`), 'utf8').match(/"(<svg.*<\/svg>)"/s)[1].replace(/\\"/g, '"');
    const list = layers(svg).map((l) => `        Layer("${l.d}", ${l.alpha}f, ${l.stroke ? l.width : 0}f)`);
    kotlin += `    val ${name} = listOf(\n${list.join(',\n')},\n    )\n\n`;
}
kotlin = kotlin.trimEnd() + '\n}\n';
writeFileSync(out, kotlin);
console.log('wrote', out);
