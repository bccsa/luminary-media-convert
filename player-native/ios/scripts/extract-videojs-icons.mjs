// Writes the video.js icons native draws (plan 05) from the SVG font video.js ships, so native
// draws the very glyphs `player-web` shows: as Swift path data for full-screen, and the play glyph
// as TypeScript for `NativeLuminaryPlayer`'s inline play button.
//
//   node player-native/ios/scripts/extract-videojs-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const font = readFileSync(join(dirname(require.resolve('video.js/package.json')), 'dist/font/VideoJS.svg'), 'utf8');
const version = require('video.js/package.json').version;

const NAMES = [
    'play', 'pause',
    'replay-5', 'replay-10', 'replay-30', 'forward-5', 'forward-10', 'forward-30',
    'fullscreen-exit', 'picture-in-picture-enter', 'audio', 'subtitles', 'volume-mute', 'volume-high',
];

const em = Number(/units-per-em="([\d.]+)"/.exec(font)[1]);
const glyphs = NAMES.map((name) => {
    const tag = new RegExp(`<glyph glyph-name="${name}"([^>]*)>`).exec(font.replace(/\s+/g, ' '));
    if (!tag) throw new Error(`video.js ${version} has no glyph ${name}`);
    const d = /\sd="([^"]*)"/.exec(tag[1])[1].trim();
    const advance = Number(/horiz-adv-x="([\d.]+)"/.exec(tag[1])?.[1] ?? em);
    const id = name.replace(/-(\w)/g, (_, c) => c.toUpperCase()).replace(/-(\d)/g, '$1');
    return `    static let ${id} = VideoJsGlyph(advance: ${advance}, path: "${d}")`;
});

writeFileSync(join(here, '../Sources/LuminaryPlayerCore/VideoJsIcons.swift'), `// Generated by player-native/ios/scripts/extract-videojs-icons.mjs from video.js ${version}'s
// icon font. Do not edit.

/// The glyphs of video.js's icon font that native full-screen draws: SVG path data in font units
/// (\`unitsPerEm\` to the em, y upwards, absolute commands).
public enum VideoJsIcons {
    public static let unitsPerEm: Double = ${em}

${glyphs.join('\n').replace(/static let/g, 'public static let')}
}
`);
const play = glyphs.length && /\sd="([^"]*)"/.exec(new RegExp('<glyph glyph-name="play"([^>]*)>').exec(font.replace(/\s+/g, ' '))[1])[1].trim();
writeFileSync(join(here, '../../src/vue/videoJsIcons.ts'), `// Generated by player-native/ios/scripts/extract-videojs-icons.mjs from video.js ${version}'s
// icon font. Do not edit.

/** The em of video.js's icon font: a glyph's path is in these units, y upwards. */
export const VIDEOJS_UNITS_PER_EM = ${em};

/** video.js's play glyph, as its big play button draws it. */
export const VIDEOJS_PLAY_PATH = '${play}';
`);
console.log(`${NAMES.length} glyphs from video.js ${version}`);
