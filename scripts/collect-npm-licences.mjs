/**
 * Collects the licence of every npm package that ships inside `app.asar`, into
 * one notice file the Licences window can display.
 *
 * The dependencies are redistributed with the application, and the permissive
 * licences they carry — MIT, ISC, BSD, Apache-2.0 — all ask for their notice to
 * travel with the copy. Nothing surfaced them, so a few hundred notices rode
 * along inside the archive where only someone unpacking it by hand would find
 * them, which honours the letter and nothing else.
 *
 * Also reports what was found, because the answer changes as dependencies do:
 * anything copyleft, or carrying no licence at all, is a decision for a person
 * rather than something to bundle quietly.
 *
 * Run by `after-pack` so the file describes the tree that actually shipped, and
 * runnable by hand — `node scripts/collect-npm-licences.mjs --report` prints the
 * summary without writing anything.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_ELECTRON = join(
    dirname(fileURLToPath(import.meta.url)),
    '..',
    'app-electron'
);

/** Licences that oblige more than a notice, so a person has to look at them. */
const COPYLEFT = /\b(GPL|LGPL|AGPL|MPL|EPL|CDDL|EUPL|OSL|CPAL|SSPL)\b/i;

/** Filenames a package may put its licence text in. */
const LICENCE_FILE = /^(LICEN[CS]E|COPYING|NOTICE)(\..*)?$/i;

/**
 * The production tree as npm resolves it — the same set electron-builder packs,
 * since `files` takes node_modules minus devDependencies.
 */
function productionTree() {
    // `npm` is `npm.cmd` on Windows, and execFileSync does not consult PATHEXT —
    // so the bare name is ENOENT there, which failed packaging on a Windows runner
    // before it reached electron-builder.
    const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
    const json = execFileSync(
        npm,
        ['ls', '--omit=dev', '--all', '--json', '--long'],
        { cwd: APP_ELECTRON, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }
    );
    return JSON.parse(json);
}

/** Flattened, de-duplicated by name@version — a package is shipped once. */
function collect(tree) {
    const found = new Map();

    (function walk(node) {
        for (const [name, dep] of Object.entries(node.dependencies ?? {})) {
            const key = `${name}@${dep.version ?? '0.0.0'}`;
            if (!found.has(key) && dep.path) {
                found.set(key, {
                    name,
                    version: dep.version ?? 'unknown',
                    path: dep.path,
                    licence: spdx(dep),
                });
            }
            walk(dep);
        }
    })(tree);

    return [...found.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/** `license` is a string on anything modern; `licenses[]` is the 2014 spelling. */
function spdx(dep) {
    if (typeof dep.license === 'string') return dep.license;
    if (dep.license?.type) return dep.license.type;
    if (Array.isArray(dep.licenses))
        return dep.licenses.map((l) => l.type ?? l).join(' OR ');
    return undefined;
}

/** The licence text as shipped, when the package carries one. */
function licenceText(pkg) {
    if (!existsSync(pkg.path)) return undefined;
    const file = readdirSync(pkg.path).find((f) => LICENCE_FILE.test(f));
    if (!file) return undefined;
    try {
        return readFileSync(join(pkg.path, file), 'utf8').trim();
    } catch {
        return undefined;
    }
}

function render(packages) {
    const head = `Third-party npm packages
========================

The application bundles the packages below. Each is listed with the licence it
declares and, where the package ships one, the licence text as published.

Generated by scripts/collect-npm-licences.mjs at packaging time.
`;

    const sections = packages.map((pkg) => {
        const text = licenceText(pkg);
        const header = `${pkg.name}@${pkg.version} — ${pkg.licence ?? 'no licence declared'}`;
        return [
            header,
            '-'.repeat(header.length),
            text ?? '(no licence text shipped with this package)',
        ].join('\n');
    });

    return [head, ...sections].join('\n\n');
}

function report(packages) {
    const byLicence = new Map();
    for (const pkg of packages) {
        const key = pkg.licence ?? 'UNDECLARED';
        byLicence.set(key, (byLicence.get(key) ?? 0) + 1);
    }

    console.log(`  ${packages.length} npm packages ship inside app.asar\n`);
    for (const [licence, count] of [...byLicence].sort((a, b) => b[1] - a[1]))
        console.log(`    ${String(count).padStart(4)}  ${licence}`);

    const attention = packages.filter(
        (p) => !p.licence || COPYLEFT.test(p.licence)
    );
    if (attention.length) {
        console.log(`\n  ${attention.length} need a person to look at them:`);
        for (const p of attention)
            console.log(
                `    - ${p.name}@${p.version}: ${p.licence ?? 'no licence declared'}`
            );
    } else {
        console.log(
            '\n  ✓ all permissive, and all satisfied by shipping the notice'
        );
    }

    const missing = packages.filter((p) => !licenceText(p));
    if (missing.length)
        console.log(
            `\n  ${missing.length} declare a licence but ship no text; the declaration is listed for those`
        );

    return attention.length;
}

const packages = collect(productionTree());
const needsAttention = report(packages);

if (!process.argv.includes('--report')) {
    const out = process.argv[2];
    if (!out) {
        console.error(
            '\nUsage: collect-npm-licences.mjs <output file> | --report'
        );
        process.exit(2);
    }
    writeFileSync(out, render(packages), 'utf8');
    console.log(`\n  wrote ${out}`);
}

// Reported, not enforced: a copyleft dependency is a decision, and failing the
// package here would block a build over something that may well be fine.
process.exitCode = 0;
void needsAttention;
